CREATE TABLE IF NOT EXISTS public.gestao_documento_config (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  retencao_anos integer NOT NULL DEFAULT 5 CHECK (retencao_anos BETWEEN 1 AND 10),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gestao_documento (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  veiculo_id uuid NULL,
  troca_id uuid NULL,
  venda_id uuid NULL,
  tipo text NOT NULL CHECK (tipo IN (
    'crlv', 'crlv_e', 'cnh', 'atpv_e', 'procuracao',
    'comprovante_endereco', 'outro'
  )),
  origem text NOT NULL CHECK (origem IN ('painel', 'troca', 'whatsapp')),
  storage_path text NOT NULL UNIQUE,
  mime text NOT NULL,
  tamanho bigint NOT NULL CHECK (tamanho > 0 AND tamanho <= 15728640),
  sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
  cifrado boolean NOT NULL DEFAULT true CHECK (cifrado = true),
  status text NOT NULL DEFAULT 'recebido'
    CHECK (status IN ('recebido', 'lido', 'confirmado', 'descartado')),
  campos_veiculo jsonb NOT NULL DEFAULT '{}'::jsonb,
  dados_pessoais_cifrados text NULL,
  retencao_ate date NOT NULL,
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz NULL,
  CONSTRAINT gestao_documento_veiculo_fk
    FOREIGN KEY (user_id, veiculo_id)
    REFERENCES public.veiculos_estoque(user_id, id),
  CONSTRAINT gestao_documento_troca_fk
    FOREIGN KEY (user_id, troca_id)
    REFERENCES public.gestao_troca(user_id, id),
  CONSTRAINT gestao_documento_venda_fk
    FOREIGN KEY (user_id, venda_id)
    REFERENCES public.veiculo_venda(user_id, veiculo_id),
  CONSTRAINT gestao_documento_path_check
    CHECK (storage_path LIKE user_id::text || '/documentos/%'),
  CONSTRAINT gestao_documento_campos_sem_pii CHECK (
    NOT (campos_veiculo ?| ARRAY[
      'proprietario', 'proprietario_nome', 'nome', 'cpf', 'cnpj',
      'cpf_cnpj', 'documento_proprietario'
    ])
    AND campos_veiculo::text !~* '"(proprietario|proprietario_nome|nome|cpf|cnpj|cpf_cnpj|documento_proprietario)"[[:space:]]*:'
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS gestao_documento_user_sha_ativo_uidx
  ON public.gestao_documento(user_id, sha256)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS gestao_documento_veiculo_idx
  ON public.gestao_documento(user_id, veiculo_id, created_at DESC)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS gestao_documento_troca_idx
  ON public.gestao_documento(user_id, troca_id, created_at DESC)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS gestao_documento_retencao_idx
  ON public.gestao_documento(retencao_ate)
  WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS public.gestao_documento_acesso (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento_id uuid NOT NULL REFERENCES public.gestao_documento(id) ON DELETE RESTRICT,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  ator_id uuid NOT NULL REFERENCES auth.users(id),
  acao text NOT NULL CHECK (acao IN (
    'upload', 'ver', 'abrir', 'baixar', 'ler', 'confirmar', 'excluir'
  )),
  detalhe jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gestao_documento_acesso_detalhe_sem_pii CHECK (
    NOT (detalhe ?| ARRAY[
      'nome', 'cpf', 'cnpj', 'cpf_cnpj', 'proprietario',
      'conteudo', 'texto_ocr', 'dados_pessoais'
    ])
    AND detalhe::text !~* '"(nome|cpf|cnpj|cpf_cnpj|proprietario|conteudo|texto_ocr|dados_pessoais)"[[:space:]]*:'
  )
);

CREATE INDEX IF NOT EXISTS gestao_documento_acesso_doc_idx
  ON public.gestao_documento_acesso(documento_id, created_at DESC);

-- Token opaco, de dez minutos e uso único. Sem políticas para authenticated:
-- somente a function, via service role, cria e consome.
CREATE TABLE IF NOT EXISTS public.gestao_documento_token (
  token_hash text PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
  documento_id uuid NOT NULL REFERENCES public.gestao_documento(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

